#!/usr/bin/env python3
"""Write a dry-run version of the content-translations migration.

    python3 supabase/scripts/make_content_translations_dry_run.py

reads   supabase/migrations/20261110000000_content_translations.sql
writes  supabase/scripts/content_translations_dry_run.sql

The dry run is the migration itself, in one transaction, followed by checks
that the new tables behave as intended, and then ROLLBACK in place of
COMMIT. Run against a database it proves the migration applies to that
database's real schema and that its guards work, and leaves nothing behind.

Re-run this script whenever the migration file changes; the dry run is
generated, never edited by hand.
"""

import sys
from pathlib import Path

MIGRATION = Path("supabase/migrations/20261110000000_content_translations.sql")
OUTPUT = Path("supabase/scripts/content_translations_dry_run.sql")

HEADER = """-- DRY RUN of supabase/migrations/20261110000000_content_translations.sql
--
-- GENERATED by supabase/scripts/make_content_translations_dry_run.py.
-- Do not edit; change the migration and regenerate.
--
-- Everything below runs in ONE transaction that ends in ROLLBACK. It creates
-- the four translation tables, checks that they behave as intended against
-- this database's real content tables, reports, and then undoes all of it.
-- Nothing is left behind, whether the checks pass or fail: any error aborts
-- the transaction, which rolls back.
--
-- While it runs (well under a second) it briefly locks the four content
-- tables it adds foreign keys to. Reads and writes to them wait for it.
--
-- A passing run ends with one row:
--     dry_run = 'OK: ...'   translation_tables_left_behind = 0
-- A failing run stops with an error (a check's message starts
-- 'DRY RUN FAILED:'), and the final row is never printed.

"""

CHECKS = """
-- ---------------------------------------------------------------------------
-- DRY-RUN CHECKS (not part of the migration)
-- ---------------------------------------------------------------------------

do $dry_run$
declare
    a_question      uuid;
    english_count   integer;
    good_options    jsonb;
    a_scenario      uuid;
    a_screen        uuid;
    an_option       uuid;
    found           integer;
begin
    -- The four tables exist, with row level security on.
    select count(*) into found
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relname in ('question_translations', 'scenario_translations',
                         'scenario_screen_translations', 'screen_option_translations')
       and c.relrowsecurity;
    if found <> 4 then
        raise exception 'DRY RUN FAILED: expected 4 new tables with RLS on, found %', found;
    end if;

    -- Exactly one policy each, all of them SELECT.
    select count(*) into found
      from pg_policies
     where schemaname = 'public'
       and tablename like '%\\_translations'
       and cmd = 'SELECT';
    if found <> 4 then
        raise exception 'DRY RUN FAILED: expected 4 SELECT policies, found %', found;
    end if;

    -- anon and authenticated can read what they should and write nothing.
    if has_table_privilege('anon', 'public.question_translations', 'SELECT') then
        raise exception 'DRY RUN FAILED: anon can read question_translations';
    end if;
    if not has_table_privilege('authenticated', 'public.question_translations', 'SELECT') then
        raise exception 'DRY RUN FAILED: authenticated cannot read question_translations';
    end if;
    if not has_table_privilege('anon', 'public.scenario_translations', 'SELECT') then
        raise exception 'DRY RUN FAILED: anon cannot read scenario_translations';
    end if;
    if has_table_privilege('authenticated', 'public.question_translations', 'INSERT')
       or has_table_privilege('authenticated', 'public.scenario_translations', 'UPDATE')
       or has_table_privilege('anon', 'public.screen_option_translations', 'DELETE')
       or has_table_privilege('anon', 'public.scenario_screen_translations', 'TRUNCATE') then
        raise exception 'DRY RUN FAILED: a client role can write to a translation table';
    end if;

    -- A real question, to test the options guard against.
    select q.id, jsonb_array_length(q.options)
      into a_question, english_count
      from public.questions q
     where jsonb_typeof(q.options) = 'array' and jsonb_array_length(q.options) >= 2
     limit 1;
    if a_question is null then
        raise exception 'DRY RUN FAILED: no question with an options array to test against';
    end if;

    -- Too few options must be rejected.
    begin
        insert into public.question_translations (question_id, locale, options)
        values (a_question, 'de', '["nur eine"]'::jsonb);
        raise exception 'DRY RUN FAILED: a translation with 1 option was accepted for a question with %', english_count;
    exception when check_violation then null;
    end;

    -- A blank option must be rejected.
    select jsonb_agg(case when n = 1 then ''::text else 'Antwort ' || n end)
      into good_options from generate_series(1, english_count) n;
    begin
        insert into public.question_translations (question_id, locale, options)
        values (a_question, 'de', good_options);
        raise exception 'DRY RUN FAILED: a blank option was accepted';
    exception when check_violation then null;
    end;

    -- The right number of non-blank options must be accepted.
    select jsonb_agg('Antwort ' || n) into good_options from generate_series(1, english_count) n;
    insert into public.question_translations (question_id, locale, question_text, options)
    values (a_question, 'de', 'Eine Frage?', good_options);

    -- A second row for the same question and language must be rejected.
    begin
        insert into public.question_translations (question_id, locale, question_text)
        values (a_question, 'de', 'Noch einmal?');
        raise exception 'DRY RUN FAILED: two translations for one question and language were accepted';
    exception when unique_violation then null;
    end;

    -- Blank text, a badly formed language tag and an empty row must be rejected.
    begin
        insert into public.question_translations (question_id, locale, question_text)
        values (a_question, 'sv', '   ');
        raise exception 'DRY RUN FAILED: blank question text was accepted';
    exception when check_violation then null;
    end;
    begin
        insert into public.question_translations (question_id, locale, question_text)
        values (a_question, 'DE_de', 'Text');
        raise exception 'DRY RUN FAILED: the language tag DE_de was accepted';
    exception when check_violation then null;
    end;
    begin
        insert into public.question_translations (question_id, locale) values (a_question, 'fr');
        raise exception 'DRY RUN FAILED: a translation row with no text at all was accepted';
    exception when check_violation then null;
    end;

    -- updated_at moves on update.
    update public.question_translations
       set explanation = 'Eine Erklärung.', updated_at = '2000-01-01'
     where question_id = a_question and locale = 'de';
    select count(*) into found
      from public.question_translations
     where question_id = a_question and locale = 'de' and updated_at > '2020-01-01';
    if found <> 1 then
        raise exception 'DRY RUN FAILED: updated_at was not set by the trigger';
    end if;

    -- Scenario, screen and option rows insert against real parents.
    select id into a_scenario from public.scenarios limit 1;
    select id into a_screen from public.scenario_screens limit 1;
    select id into an_option from public.screen_options limit 1;
    if a_scenario is null or a_screen is null or an_option is null then
        raise exception 'DRY RUN FAILED: no scenario, screen or option to test against';
    end if;
    insert into public.scenario_translations (scenario_id, locale, title) values (a_scenario, 'de', 'Ein Titel');
    insert into public.scenario_screen_translations (screen_id, locale, text) values (a_screen, 'de', 'Ein Text');
    insert into public.screen_option_translations (option_id, locale, text) values (an_option, 'de', 'Eine Antwort');
    begin
        insert into public.scenario_translations (scenario_id, locale, title) values (a_scenario, 'sv', ' ');
        raise exception 'DRY RUN FAILED: a blank scenario title was accepted';
    exception when check_violation then null;
    end;

    -- A translation for a row that does not exist must be rejected.
    begin
        insert into public.screen_option_translations (option_id, locale, text)
        values ('00000000-0000-0000-0000-000000000000', 'de', 'Waise');
        raise exception 'DRY RUN FAILED: a translation for a missing option was accepted';
    exception when foreign_key_violation then null;
    end;
end
$dry_run$;

rollback;

-- Reached only if nothing above failed. Also shows that nothing was kept.
select 'OK: migration applied, all checks passed, then rolled back' as dry_run,
       (select count(*)
          from information_schema.tables
         where table_schema = 'public'
           and table_name in ('question_translations', 'scenario_translations',
                              'scenario_screen_translations', 'screen_option_translations')
       ) as translation_tables_left_behind;
"""


def main():
    if not MIGRATION.exists():
        print(f"Run from the repo root: {MIGRATION} not found.")
        return 2
    text = MIGRATION.read_text(encoding="utf-8")

    start = text.index("\nbegin;\n")
    end = text.index("\ncommit;\n")
    body = text[start + 1:end + 1]  # from "begin;" up to, not including, "commit;"
    if body.count("commit;") or "rollback;" in body:
        print("The migration body contains a transaction statement the dry run cannot wrap.")
        return 2

    OUTPUT.write_text(HEADER + body + CHECKS, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(body.splitlines())} migration lines + checks, ending in ROLLBACK)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
